fn inventory(files: &[(&str, &str)]) -> Vec<FileFacts> {
    files
        .iter()
        .map(|(path, source)| {
            let facts =
                parse_python(path, source, &blake3::hash(source.as_bytes()).to_hex()).unwrap();
            assert!(
                facts.diagnostics.is_empty(),
                "{path}: {:?}",
                facts.diagnostics
            );
            facts
        })
        .collect()
}

fn contextualize(mut facts: Vec<FileFacts>) -> Vec<FileFacts> {
    let context = PythonContext::from_facts(&facts);
    for file in &mut facts {
        context.apply(file);
    }
    facts
}

fn pairs(graph: &GraphSnapshot, relation: &str) -> Vec<(String, String)> {
    graph
        .edges
        .iter()
        .filter(|e| e.relation == relation)
        .map(|e| {
            let source = graph.nodes.iter().find(|n| n.id == e.source).unwrap();
            let target = graph.nodes.iter().find(|n| n.id == e.target).unwrap();
            (
                source.label.clone(),
                format!(
                    "{}:{}",
                    target.file,
                    target.qualified_name.as_deref().unwrap_or(&target.label)
                ),
            )
        })
        .collect()
}

#[test]
fn package_and_public_alias_chains_resolve_to_original_symbols_and_members() {
    let files = inventory(&[
        (
            "src/pkg/impl.py",
            "def execute(): pass\nclass Engine:\n    @staticmethod\n    def build(): pass\n",
        ),
        (
            "src/pkg/api.py",
            "from .impl import execute as Public, Engine as PublicType\n",
        ),
        (
            "src/pkg/__init__.py",
            "from .api import Public as entry, PublicType as Shape\nimport pkg.impl as backend\n",
        ),
        (
            "app.py",
            "from pkg import entry, Shape, backend\nimport pkg as package\ndef run():\n    entry()\n    package.entry()\n    Shape.build()\n    backend.execute()\n",
        ),
    ]);
    let native_ids: Vec<_> = files
        .iter()
        .flat_map(|f| f.nodes.iter().map(|n| n.id.clone()))
        .collect();
    let files = contextualize(files);
    assert_eq!(
        native_ids,
        files
            .iter()
            .flat_map(|f| f.nodes.iter().map(|n| n.id.clone()))
            .collect::<Vec<_>>()
    );
    let dir = tempdir().unwrap();
    let mut store = Store::create(&dir.path().join("index.db")).unwrap();
    store
        .apply_native("fixture-root", files, vec![], Coverage::default())
        .unwrap();
    let graph = store.snapshot().unwrap();
    let calls = pairs(&graph, "calls");
    assert_eq!(calls.len(), 4, "{calls:?}");
    assert_eq!(
        calls
            .iter()
            .filter(|(_, target)| target == "src/pkg/impl.py:execute")
            .count(),
        3
    );
    assert!(calls.contains(&("run".into(), "src/pkg/impl.py:Engine.build".into())));
    assert!(pairs(&graph, "imports").contains(&("app".into(), "src/pkg/impl.py:execute".into())));
    assert!(
        pairs(&graph, "re_exports")
            .contains(&("pkg.api".into(), "src/pkg/impl.py:pkg.impl".into()))
    );
}

#[test]
fn forwarding_does_not_infer_dynamic_or_shadowed_exports() {
    for package in [
        "from .impl import execute as entry\nentry = factory()\n",
        "from .impl import execute as entry\ndel entry\n",
        "if enabled:\n    from .impl import execute as entry\n",
        "from .impl import execute as entry\nfrom .other import execute as entry\n",
        "from .impl import *\n__all__ = ['entry']\n",
        "from .impl import execute as _hidden\n__all__ = compute_exports()\n",
        "from .impl import execute as entry\nglobals()['entry'] = replacement\n",
        "from .impl import execute as entry\nentry.attribute = replacement\n",
    ] {
        let files = contextualize(inventory(&[
            ("pkg/impl.py", "def execute(): pass\n"),
            ("pkg/other.py", "def execute(): pass\n"),
            ("pkg/__init__.py", package),
            (
                "consumer.py",
                "from pkg import entry, _hidden\ndef run():\n    entry()\n    _hidden()\n",
            ),
        ]));
        let dir = tempdir().unwrap();
        let mut store = Store::create(&dir.path().join("index.db")).unwrap();
        store
            .apply_native("fixture-root", files, vec![], Coverage::default())
            .unwrap();
        assert!(
            !pairs(&store.snapshot().unwrap(), "calls")
                .iter()
                .any(|(source, _)| source == "run"),
            "{package}"
        );
    }
    // __all__ mutations cannot erase an explicit named import, or invent a star export.
    let files = contextualize(inventory(&[
        ("pkg/impl.py", "def execute(): pass\n"),
        (
            "pkg/__init__.py",
            "from .impl import execute as entry\n__all__ = []\n__all__.extend(compute_exports())\n",
        ),
        ("consumer.py", "from pkg import entry\ndef run(): entry()\n"),
        ("star.py", "from pkg import *\ndef run_star(): entry()\n"),
    ]));
    assert_eq!(
        reference(&files[2], "run", "entry", "calls").candidate_keys,
        ["python:pkg.impl:execute"]
    );
    assert!(
        reference(&files[3], "run_star", "entry", "calls")
            .candidate_keys
            .is_empty()
    );
}

#[test]
