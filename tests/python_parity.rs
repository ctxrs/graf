#[test]
fn imported_class_and_relative_module_members_resolve_without_function_guessing() {
    let dir = tempdir().unwrap();
    let mut store = Store::create(&dir.path().join("index.db")).unwrap();
    let provider = parse_python("src/pkg/model.py", "class Service:\n    @staticmethod\n    def work(): pass\ndef Factory():\n    def work(): pass\ndef helper(): pass\n", "provider").unwrap();
    let consumer = parse_python("src/pkg/api.py", "from .model import Service, Factory\nfrom . import model\ndef run():\n    Service.work()\n    Factory.work()\n    model.helper()\n", "consumer").unwrap();
    let service = node(&provider, "Service.work").id.clone();
    let nested = node(&provider, "Factory.work").id.clone();
    let helper = node(&provider, "helper").id.clone();
    store
        .apply_native(
            "fixture-root",
            vec![provider, consumer],
            vec![],
            Coverage::default(),
        )
        .unwrap();
    let graph = store.snapshot().unwrap();
    let calls: Vec<_> = graph
        .edges
        .iter()
        .filter(|e| e.relation == "calls")
        .collect();
    assert_eq!(calls.len(), 2);
    assert!(calls.iter().any(|e| e.target == service));
    assert!(calls.iter().any(|e| e.target == helper));
    assert!(!calls.iter().any(|e| e.target == nested));
    // Replacing the class with a function removes the old member alias and edge.
    let changed = parse_python(
        "src/pkg/model.py",
        "def Service():\n    def work(): pass\ndef helper(): pass\n",
        "changed",
    )
    .unwrap();
    store
        .apply_native("fixture-root", vec![changed], vec![], Coverage::default())
        .unwrap();
    assert!(
        !store
            .snapshot()
            .unwrap()
            .edges
            .iter()
            .any(|e| e.relation == "calls" && e.target == service)
    );
}

