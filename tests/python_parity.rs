fn parse(source: &str) -> FileFacts {
    let facts = parse_python("src/pkg/sample.py", source, "fixture").unwrap();
    assert!(facts.diagnostics.is_empty(), "{:?}", facts.diagnostics);
    facts
}

fn node<'a>(facts: &'a FileFacts, name: &str) -> &'a Node {
    facts
        .nodes
        .iter()
        .find(|n| n.qualified_name.as_deref() == Some(name))
        .unwrap()
}

fn reference<'a>(facts: &'a FileFacts, owner: &str, label: &str, relation: &str) -> &'a Reference {
    let id = &node(facts, owner).id;
    facts
        .references
        .iter()
        .find(|r| r.source == *id && r.label == label && r.relation == relation)
        .unwrap()
}

fn context(facts: &FileFacts, owner: &str, label: &str, expected: &str) {
    let reference = reference(facts, owner, label, "references");
    assert!(
        node(facts, owner).metadata["python_references"]
            .as_array()
            .unwrap()
            .iter()
            .any(|e| { e["reference_id"] == reference.id && e["context"] == expected })
    );
}

#[test]
fn rationale_uses_ast_locations_and_actual_nested_owners() {
    let facts = parse(
        r##"#!/usr/bin/env python3
# coding: utf-8
"""Keep a local journal because network access is optional."""
class Journal:
    # introductory comment
    """Entries survive retries because append operations are idempotent."""
    @property
    def size(self):
        """Return a stable count because callers compare successive reads."""
        # WHY: exclude pending writes until they are committed
        def pending():
            """Keep pending writes separate because their transaction can fail."""
            pass
        return 0
fake = """
# NOTE: this is string content, not a comment
"""
# FIXME: remove the compatibility path after migration
"##,
    );
    let rationale: Vec<_> = facts
        .nodes
        .iter()
        .filter(|n| n.kind == "rationale")
        .collect();
    assert_eq!(rationale.len(), 6);
    assert!(!rationale.iter().any(|n| n.label.contains("string content")));
    let module_doc = rationale
        .iter()
        .find(|n| n.label.contains("local journal"))
        .unwrap();
    assert_eq!(module_doc.line, Some(3));
    for (text, owner) in [
        ("Entries survive", "Journal"),
        ("stable count", "Journal.size"),
        ("WHY:", "Journal.size"),
        ("pending writes separate", "Journal.size.pending"),
    ] {
        let rationale = rationale.iter().find(|n| n.label.contains(text)).unwrap();
        assert!(facts.edges.iter().any(|e| e.source == rationale.id
            && e.target == node(&facts, owner).id
            && e.relation == "rationale_for"));
    }
    assert!(
        rationale
            .iter()
            .all(|n| n.metadata["source_text"].is_string())
    );
}

#[test]
fn only_docstrings_and_selected_comments_become_rationale() {
    for source in [
        "x = 1\n'''This is a later expression and never a module docstring.'''\n",
        "b'''Bytes are not documentation even if this text is long.'''\n",
        "f'''Interpolation is not documentation even if this text is long.'''\n",
        "'''Tiny.'''\n# ordinary prose comment\n",
    ] {
        assert!(
            !parse(source).nodes.iter().any(|n| n.kind == "rationale"),
            "{source}"
        );
    }
    let facts = parse("('This rationale is split ' 'across adjacent literals for readability.')\n");
    assert_eq!(
        facts.nodes.iter().filter(|n| n.kind == "rationale").count(),
        1
    );
    for prefix in [
        "NOTE",
        "IMPORTANT",
        "HACK",
        "WHY",
        "RATIONALE",
        "TODO",
        "FIXME",
    ] {
        let facts = parse(&format!("# {prefix}: preserve the source evidence\n"));
        assert_eq!(
            facts.nodes.iter().filter(|n| n.kind == "rationale").count(),
            1
        );
    }
}

